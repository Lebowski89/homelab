@pytest.mark.parametrize("missing", ["stub", "output", "nss-provider"])
def test_missing_runtime_capabilities_retain_the_previous_resolver_file(system_run, missing):
    overrides = rpm_inputs()
    if missing == "stub":
        overrides["fixture_resolver_ports"] = []
    elif missing == "output":
        overrides["fixture_files"].pop("/run/systemd/resolve/stub-resolv.conf")
    else:
        overrides.update(system_resolved_disable_stub=True, fixture_resolver_nss_missing=True)
    result, calls, state = system_run(tags="system_resolved", overrides=overrides)
    assert result.returncode != 0
    assert calls
    assert not state.get("resolver_links")
    assert not any(call["module"] == "file" and call["options"].get("state") == "link" for call in calls)


