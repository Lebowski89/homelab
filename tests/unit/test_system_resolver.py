"""Exercise resolver routing and ownership with the existing isolated host fixture."""

import pytest

pytest_plugins = ["test_system"]
pytestmark = pytest.mark.integration


def rpm_inputs(distro="Rocky", version="10.2", backend="dnf", **overrides):
    return {
        "ansible_facts": {
            "distribution": distro,
            "distribution_version": version,
            "distribution_major_version": version.split(".")[0],
            "os_family": "RedHat",
            "pkg_mgr": backend,
            "system": "Linux",
            "service_mgr": "systemd",
            "virtualization_type": "kvm",
        },
        "system_resolved_enabled": True,
        "system_resolved_manage_resolv_conf": True,
        "fixture_services": {"NetworkManager.service": {"state": "running"}},
        "fixture_resolver_dns_mode": "systemd-resolved",
        "fixture_files": {
            "/etc/resolv.conf": "# Generated by NetworkManager\nnameserver 192.0.2.53\n",
            "/run/systemd/resolve/stub-resolv.conf": "nameserver 127.0.0.53\n",
            "/run/systemd/resolve/resolv.conf": "nameserver 192.0.2.53\n",
            "/etc/nsswitch.conf": "hosts: files resolve [!UNAVAIL=return] dns myhostname\n",
        },
        **overrides,
    }


def success(result):
    assert result.returncode == 0, result.stdout + result.stderr


@pytest.mark.parametrize(
    "distro,version,backend,packages",
    [
        ("Rocky", "10.2", "dnf", None),
        ("Fedora", "43", "dnf", None),
        ("Fedora", "44", "dnf5", ["operator-reviewed-resolver"]),
    ],
)
def test_rpm_resolver_routes_packages_preserves_owners_and_converges(system_run, distro, version, backend, packages):
    overrides = rpm_inputs(distro, version, backend)
    if packages is not None:
        overrides["system_resolved_packages"] = packages
    result, calls, state = system_run(tags="system_resolved", overrides=overrides)
    success(result)
    installs = [call for call in calls if call["module"] in {"apt", "dnf"}]
    assert len(installs) == 1 and installs[0]["module"] == "dnf"
    assert installs[0]["options"]["name"] == (packages or ["systemd-resolved"])
    assert installs[0]["options"]["use_backend"] == ("dnf5" if backend == "dnf5" else "dnf4")
    assert installs[0]["options"]["state"] == "present"
    assert not installs[0]["options"]["disable_gpg_check"] and not installs[0]["options"]["allowerasing"]
    assert "DEBIAN_FRONTEND" not in str(installs[0]["environment"])
    assert not any(call["module"] == "lineinfile" for call in calls)
    assert not any(str(call["options"].get("dest", "")).startswith("/etc/NetworkManager/") for call in calls)
    assert state["resolver_links"]["/etc/resolv.conf"] == "/run/systemd/resolve/stub-resolv.conf"
    refreshes = [call["options"]["argv"] for call in calls if call["module"] == "command" and call["options"]["argv"][0] == "nmcli"]
    assert refreshes == [["nmcli", "general", "reload", "dns-full"]]
    result, calls, _ = system_run(tags="system_resolved", overrides=overrides)
    success(result)
    assert "changed=0" in result.stdout
    assert not any(call["options"].get("state") == "restarted" for call in calls)
    assert not any(call["module"] == "command" and call["options"]["argv"][0] == "nmcli" for call in calls)


@pytest.mark.parametrize(
    "unsafe",
    [
        "publisher",
        "inactive-manager",
        "tailscale",
        "file-owner",
        "writable-file",
        "foreign-link",
        "nss",
        "nss-order",
        "listener",
        "nss-owner",
        "old-fedora",
        "lxc",
    ],
)
def test_rpm_ownership_conflicts_fail_before_any_baseline_mutation(system_run, unsafe):
    overrides = rpm_inputs()
    if unsafe == "publisher":
        overrides["fixture_resolver_dns_mode"] = "dnsmasq"
    elif unsafe == "inactive-manager":
        overrides["fixture_services"] = {}
    elif unsafe == "tailscale":
        overrides["fixture_files"]["/etc/resolv.conf"] = (
            "# resolv.conf generated by tailscale\nnameserver 192.0.2.1\n# Generated by NetworkManager\n"
        )
    elif unsafe == "file-owner":
        overrides["fixture_file_owners"] = {"/etc/resolv.conf": 1001}
    elif unsafe == "writable-file":
        overrides["fixture_file_modes"] = {"/etc/resolv.conf": "0664"}
    elif unsafe == "foreign-link":
        overrides["fixture_link_targets"] = {"/etc/resolv.conf": "/run/other-owner/resolv.conf"}
    elif unsafe in {"nss", "nss-order"}:
        overrides["system_resolved_disable_stub"] = True
        overrides["fixture_files"]["/etc/nsswitch.conf"] = (
            "hosts: files dns myhostname\n" if unsafe == "nss" else "hosts: files dns resolve\n"
        )
    elif unsafe == "listener":
        overrides["fixture_resolver_ports"] = [{"address": "0.0.0.0", "port": 53, "pid": 999}]
    elif unsafe == "nss-owner":
        overrides["system_resolved_manage_nsswitch"] = True
    elif unsafe == "old-fedora":
        overrides["ansible_facts"].update(distribution="Fedora", distribution_version="42", distribution_major_version="42")
    else:
        overrides["ansible_facts"]["virtualization_type"] = "lxc"
    result, calls, _ = system_run(tags="system", overrides=overrides)
    assert result.returncode != 0
    assert calls
    assert {call["module"] for call in calls} <= {
        "stat",
        "setup",
        "package_facts",
        "service_facts",
        "slurp",
        "command",
        "community.general.listen_ports_facts",
    }
    assert all(call["options"]["argv"][0] in {"busctl", "systemctl"} for call in calls if call["module"] == "command")


@pytest.mark.parametrize("disable_stub", [False, True])
@pytest.mark.parametrize("distro,version,backend", [("Rocky", "10.2", "dnf"), ("Fedora", "45", "dnf5")])
def test_rpm_fresh_check_mode_only_inspects_and_defers_runtime_work(system_run, disable_stub, distro, version, backend):
    overrides = rpm_inputs(distro, version, backend, system_resolved_disable_stub=disable_stub)
    overrides["fixture_files"].pop("/run/systemd/resolve/stub-resolv.conf")
    overrides["fixture_files"].pop("/run/systemd/resolve/resolv.conf")
    result, calls, state = system_run(tags="system_resolved", check=True, overrides=overrides)
    success(result)
    assert "deferred" in result.stdout.lower()
    assert {call["module"] for call in calls} <= {
        "stat",
        "setup",
        "package_facts",
        "service_facts",
        "slurp",
        "command",
        "community.general.listen_ports_facts",
    }
    assert not state


def test_disabled_stub_keeps_nss_owned_and_verifies_the_installed_provider(system_run):
    result, calls, state = system_run(tags="system_resolved", overrides=rpm_inputs(system_resolved_disable_stub=True))
    success(result)
    assert state["resolver_links"]["/etc/resolv.conf"] == "/run/systemd/resolve/resolv.conf"
    assert any(call["options"].get("argv") == ["getent", "-s", "resolve", "hosts", "localhost"] for call in calls)
    assert not any(call["module"] == "lineinfile" for call in calls)


def test_prepared_host_retains_explicit_output_empty_packages_and_external_dropins(system_run):
    overrides = rpm_inputs(
        system_resolved_resolv_conf_target="/run/systemd/resolve/resolv.conf",
        system_resolved_manage_resolv_conf=False,
        system_resolved_packages=[],
        system_resolved_service_name="systemd-resolved.service",
        fixture_services={"NetworkManager.service": {"state": "running"}, "systemd-resolved.service": {"state": "running"}},
        fixture_link_targets={"/etc/resolv.conf": "/run/systemd/resolve/resolv.conf"},
    )
    legacy = "/etc/systemd/resolved.conf.d/no-stub-listener.conf"
    overrides["fixture_files"][legacy] = "[Resolve]\nDNSStubListener=no\n"
    result, calls, _ = system_run(tags="system_resolved", overrides=overrides)
    success(result)
    assert not any(call["module"] in {"apt", "dnf", "lineinfile"} for call in calls)
    assert not any(
        call["module"] == "file" and (call["options"].get("path") == legacy or call["options"].get("state") == "link") for call in calls
    )


