@pytest.mark.parametrize("installed", [False, True])
def test_fedora_package_scripts_cannot_take_unselected_resolver_ownership(system_run, installed):
    overrides = rpm_inputs("Fedora", "44", "dnf5", system_resolved_manage_resolv_conf=False)
    overrides["fixture_link_targets"] = {"/etc/resolv.conf": "/run/systemd/resolve/stub-resolv.conf"}
    if installed:
        overrides["fixture_packages"] = {"systemd-resolved": [{"version": "fixture"}]}
    result, calls, _ = system_run(tags="system_resolved", overrides=overrides)
    assert calls
    if installed:
        success(result)
    else:
        assert result.returncode != 0
        assert not any(call["module"] in {"apt", "dnf", "file", "copy", "systemd_service"} for call in calls)
